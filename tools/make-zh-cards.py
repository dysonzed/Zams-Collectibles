def cell(v):
    return '"' + v.replace('"', '""') + '"' if any(c in v for c in ',"') else v


lines = [f"set_{k}_name,{cell(v)}" for k, v in SETS.items()]
lines += [f"rarity_{k},{cell(v)}" for k, v in RARITIES.items()]
for set_id, cards in CARDS.items():
    for n, (name, text, flavor) in enumerate(cards, 1):
        key = f"card_{set_id}_{n:02d}"
        lines.append(f"{key}_name,{cell(name)}")
        if text:
            lines.append(f"{key}_text,{cell(text)}")
        lines.append(f"{key}_flavor,{cell(flavor)}")

path = f"{root}/Localization/zh.csv"
keep = [l for l in open(path, encoding="utf-8").read().splitlines()
        if not l.startswith(("set_", "rarity_", "card_rustwave", "card_doomed", "card_oxygen", "card_grace", "card_brood",
                             "card_neural", "card_fates", "card_ascension", "card_singularity", "card_recursion"))]
open(path, "w", encoding="utf-8").write("\n".join(keep + lines) + "\n")
print(len(lines), "lines")
